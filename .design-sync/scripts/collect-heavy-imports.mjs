// Collect every NAMED/DEFAULT import pulled from the heavy modules across
// frontend/src/shared, then GENERATE .design-sync/stubs/empty.mjs exporting
// exactly those names (all = the self-returning proxy P). ESM so esbuild
// static-binds the names; a CJS proxy loses them through __toESM.
//
// Anchored regex: `\{([^{}]*)\}\s*from 'mod'` captures the single import's
// brace group immediately before `from 'mod'` ([^{}] can't cross another
// import's braces, and matches newlines for multiline imports). Re-run on
// re-sync if heavy imports change; a missing name otherwise surfaces as a loud
// esbuild "No matching export".
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'frontend/src/shared';
const HEAVY = ['@assistant-ui/react', '@assistant-ui/react-ai-sdk', '@assistant-ui/react-lexical',
  '@tiptap/react', '@tiptap/starter-kit', '@tiptap/extension-text-style', 'streamdown', 'ai', 'zod'];
const esc = (m) => m.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const reMod = `(?:${HEAVY.map(esc).join('|')})`;

function walk(d, out = []) {
  for (const e of readdirSync(d)) {
    const p = join(d, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|tsx)$/.test(e)) out.push(p);
  }
  return out;
}

const named = new Set(), namespaces = [];
const reNamed = new RegExp(`\\{([^{}]*)\\}\\s*from\\s*['"]${reMod}['"]`, 'g');
const reDefault = new RegExp(`import\\s+([A-Za-z_$][\\w$]*)\\s*(?:,\\s*\\{[^{}]*\\})?\\s*from\\s*['"]${reMod}['"]`, 'g');
const reNs = new RegExp(`import\\s+\\*\\s+as\\s+([A-Za-z_$][\\w$]*)\\s*from\\s*['"]${reMod}['"]`, 'g');
let any = false;
for (const f of walk(ROOT)) {
  const src = readFileSync(f, 'utf8');
  let m;
  while ((m = reNamed.exec(src))) {
    any = true;
    for (let n of m[1].split(',')) {
      n = n.replace(/^\s*type\s+/, '').trim().split(/\s+as\s+/)[0].trim();
      if (n && /^[A-Za-z_$][\w$]*$/.test(n)) named.add(n);
    }
  }
  while ((m = reDefault.exec(src))) named.add('default:' + m[1]); // marker; default handled separately
  while ((m = reNs.exec(src))) namespaces.push(`${m[1]} @ ${f.replace(ROOT + '/', '')}`);
}
const hasDefault = [...named].some((n) => n.startsWith('default:'));
const realNamed = [...named].filter((n) => !n.startsWith('default:')).sort();

console.error('NAMED_COUNT', realNamed.length, '| hasDefault', hasDefault, '| namespaces', namespaces.length, namespaces);

const STUB = `// AUTO-GENERATED by .ds-sync/collect-heavy-imports.mjs — do not hand-edit names.
// ESM universal stub for heavy libs (assistant-ui / @tiptap / streamdown / ai / zod).
// MUST be ESM: esbuild static-binds ESM named imports, but runs CJS through
// __toESM (copies only own enumerable props — none on a proxy) so a CJS proxy
// would bind every named import to undefined and crash IIFE eval. P is a
// self-returning proxy: every get/call/construct yields P, so module-top-level
// use (z.object({...}), StarterKit.configure()) never throws at load. Components
// that truly render these libs fail at RENDER → auto floor card (intended).
const P = new Proxy(function stub() {}, {
  get(_t, k) {
    if (k === '__esModule') return true;
    if (k === 'then') return undefined;
    if (k === Symbol.toPrimitive) return () => '';
    if (k === Symbol.toStringTag) return 'Module';
    if (k === Symbol.iterator) return function* () {};
    return P;
  },
  apply: () => P,
  construct: () => P,
});
export default P;
export {
${realNamed.map((n) => `  P as ${n},`).join('\n')}
};
`;
writeFileSync('.design-sync/stubs/empty.mjs', STUB);
console.error('wrote .design-sync/stubs/empty.mjs with', realNamed.length, 'named exports');
