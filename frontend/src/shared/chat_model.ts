// Sprint 19 — chat_tool_call row + CRUD inputs.

export interface ChatToolCall {
  id: number
  message_id: number
  /** Anthropic toolu_xxx. MUST match across `tool_use` → `tool_result`
   *  round-trip in the LLM message stream. UNIQUE per (message_id). */
  tool_use_id: string
  tool_name: string
  /** Original LLM-proposed input, serialized JSON. */
  input_json: string
  /** Set only when tier was 'edit' and the user changed the input via the
   *  ConfirmToolDialog. The tool handler receives this as effective input;
   *  the result envelope returned to the LLM includes
   *  `{ user_edited: true, original_input, final_input }` so the model
   *  knows what was actually executed. */
  user_edited_input_json: string | null
  /** Tool handler's `ToolResult` serialized as JSON. Null until completion. */
  output_json: string | null
  status: ToolCallStatus
  duration_ms: number | null
  confirmation_tier: ConfirmationTier
  /** Epoch ms when the user clicked Confirm. Null for silent / canceled. */
  confirmed_at: number | null
  /** task 06-08-chat Bug 2 — character offset into the parent assistant
   *  message's `content` at which this tool call was proposed (= the running
   *  buffer length when the harness saw the `tool_use` block, i.e. after this
   *  iter's text but before the next iter's). The renderer splits `content` at
   *  these offsets to interleave tool chips in time order ("text → tool → more
   *  text") instead of stacking all chips below the body. Null for rows written
   *  before v5 (and for non-custom-api / non-harness paths) → renderer falls
   *  back to the legacy "all chips after the body" layout. */
  content_offset: number | null
  /** Phase 03b (v10) — write-tool approval outcome: 'approved' / 'edited' / 'rejected'
   *  for AI SDK Gateway HITL write tools; NULL for read tools + legacy harness rows.
   *  Optional: absent on rows read from a pre-v10 DB / older serve-api JSON. */
  approval_status?: string | null
  /** Phase 03b (v10) — sha256 of the approved input (the domain ApprovalGuard binding).
   *  NULL for read tools + legacy rows. Optional (see approval_status). */
  approval_hash?: string | null
  /** Phase 04a (v11) — the A2UI render payload (component + props + audit, protocol §3) the
   *  rich tool card showed for an AI SDK Gateway write tool. NULL for read tools / legacy rows
   *  / flag-off writes. Optional (absent on rows from a pre-v11 DB / older serve-api JSON). */
  ui_payload_json?: string | null
  /** Phase 04b (v12) — outbound-send (email_prepare_send) only: sha256 of the canonical outbound
   *  payload that bound the approved content to what was sent. NULL for every other tool / legacy
   *  row. Optional (absent on rows from a pre-v12 DB / older serve-api JSON). */
  content_hash?: string | null
  /** Phase 04b (v12) — outbound-send only: the one-shot idempotency key the Python send ledger
   *  keyed on (a replay never re-sends). NULL otherwise. Optional (see content_hash). */
  idempotency_key?: string | null
  /** S2 W1 (v18) — exec tools only: the PolicyRule id that auto-allowed the run without a card
   *  (approval_status='auto_whitelist'). NULL for card-approved / read / legacy rows. Optional
   *  (absent on rows from a pre-v18 DB / older serve-api JSON). */
  whitelist_rule_id?: number | null
  created_at: number
  updated_at: number
}

export interface AppendToolCallInput {
  messageId: number
  toolUseId: string
  toolName: string
  inputJson: string
  confirmationTier: ConfirmationTier
  /** Initial status — usually 'pending' for preview/edit tiers, 'running'
   *  for silent. */
  status: ToolCallStatus
  /** task 06-08-chat Bug 2 — running content length at the moment the harness
   *  saw the tool_use block (insertion point for time-ordered interleaving).
   *  Omitted by callers that don't track it → persisted as NULL. */
  contentOffset?: number
}

export interface UpdateToolCallPatch {
  status?: ToolCallStatus
  outputJson?: string | null
  durationMs?: number | null
  userEditedInputJson?: string | null
  confirmedAt?: number | null
  /** Phase 03b (v10) — write-tool approval outcome ('approved'/'edited'/'rejected'). */
  approvalStatus?: string | null
  /** Phase 03b (v10) — sha256 of the approved input (domain ApprovalGuard binding). */
  approvalHash?: string | null
  /** Phase 04a (v11) — the A2UI render payload (JSON) the rich tool card showed. */
  uiPayloadJson?: string | null
  /** Phase 04b (v12) — outbound-send content hash (sha256 of the canonical outbound payload). */
  contentHash?: string | null
  /** Phase 04b (v12) — outbound-send one-shot idempotency key (the send ledger key). */
  idempotencyKey?: string | null
  /** S2 W1 (v18) — exec whitelist rule id (approval_status='auto_whitelist'). */
  whitelistRuleId?: number | null
}

